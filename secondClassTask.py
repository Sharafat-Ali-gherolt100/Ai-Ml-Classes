GoalAmount = int(input('Enter the Goal Amount'))
WeeklyAmount = int(input('Enter the Weekly Amount'))
TotalAmount = 0;
TotalWeeks = 0;


while True:
    TotalAmount > GoalAmount
    TotalAmount = TotalAmount + WeeklyAmount
    TotalWeeks = TotalWeeks + 1
    if(TotalAmount >= GoalAmount):
        print('You have reached your goal')
        break
    print('Goal Amount ', GoalAmount)
    print('Total Amount ', TotalAmount)
    print('Total Weeks ', TotalWeeks)
   
    
    